with open("citizen-dashboard/src/lib/LanguageContext.tsx", "r", encoding="utf-8") as f:
    lines = f.readlines()

new_lines = []
in_en = False
in_hi = False
in_te = False

for line in lines:
    if line.strip() == "en: {":
        in_en = True
        new_lines.append(line)
        continue
    elif line.strip() == "hi: {":
        in_hi = True
        new_lines.append(line)
        continue
    elif line.strip() == "te: {":
        in_te = True
        new_lines.append(line)
        continue
        
    if in_en and line.strip().startswith(('poweredBy:', 'intelligentCivic:', 'infraForIndia:', 'heroDesc:', 'reportAnIssue:', 'govPortalAccess:', 'trackStatus:')):
        continue
    if in_hi and line.strip().startswith(('poweredBy:', 'intelligentCivic:', 'infraForIndia:', 'heroDesc:', 'reportAnIssue:', 'govPortalAccess:', 'trackStatus:')):
        continue
    if in_te and line.strip().startswith(('poweredBy:', 'intelligentCivic:', 'infraForIndia:', 'heroDesc:', 'reportAnIssue:', 'govPortalAccess:', 'trackStatus:')):
        continue

    if line.strip() == "},":
        in_en = False
        in_hi = False
        in_te = False
    
    new_lines.append(line)

content = "".join(new_lines)

